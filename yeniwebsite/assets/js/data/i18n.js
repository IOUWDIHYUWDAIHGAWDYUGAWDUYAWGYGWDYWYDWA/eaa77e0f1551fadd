window.VYBOT_LANG = {
  current: 'en',
  init() {
    const saved = localStorage.getItem('vybot-lang');
    const browser = (navigator.language || 'en').toLowerCase().startsWith('tr') ? 'tr' : 'en';
    this.set(saved || browser, false);
  },
  set(lang, persist = true) {
    this.current = lang;
    if (persist) localStorage.setItem('vybot-lang', lang);
    document.documentElement.lang = lang === 'tr' ? 'tr' : 'en';
    this.apply();
    window.dispatchEvent(new CustomEvent('vybot:langchange', { detail: { lang } }));
  },
  toggle() { this.set(this.current === 'en' ? 'tr' : 'en'); },
  t(key) {
    const dict = window.VYBOT_I18N[this.current] || window.VYBOT_I18N.en;
    return dict[key] ?? window.VYBOT_I18N.en[key] ?? key;
  },
  apply() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = this.t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
      el.setAttribute('placeholder', this.t(el.getAttribute('data-i18n-ph')));
    });
  },
};
